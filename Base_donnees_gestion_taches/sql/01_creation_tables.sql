-- Suppression dans l'ordre inverse des dépendances (ignore les tables absentes)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('TACHE_PARENTE', 'PERIODE', 'ASSIGNATION', 'TACHE_TERMINEE',
                                 'TACHE_ACTIVE', 'LISTE_DE_TACHES', 'PROJET', 'SCORE_NIVEAU',
                                 'UTILISATEUR'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Utilisateurs et gamification
-- ---------------------------------------------------------------------
CREATE TABLE utilisateur (
  id_user           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nom               VARCHAR2(50)  NOT NULL,
  prenom            VARCHAR2(50)  NOT NULL,
  login             VARCHAR2(30)  NOT NULL,
  addresse          VARCHAR2(200),
  date_naissance    DATE,
  date_inscription  DATE DEFAULT SYSDATE NOT NULL,
  mdp               VARCHAR2(255) NOT NULL,          -- empreinte du mot de passe, jamais en clair
  CONSTRAINT pk_utilisateur PRIMARY KEY (id_user),
  CONSTRAINT uq_utilisateur_login UNIQUE (login),
  CONSTRAINT ck_utilisateur_dates CHECK (date_naissance IS NULL OR date_naissance < date_inscription)
);

-- Association 1,1 – 1,1 (ATTRIBUER) : la clé de SCORE_NIVEAU est aussi celle de l'utilisateur
CREATE TABLE score_niveau (
  id_user  NUMBER,
  score    NUMBER(8) DEFAULT 0 NOT NULL,
  niveau   NUMBER(3) DEFAULT 1 NOT NULL,
  CONSTRAINT pk_score_niveau PRIMARY KEY (id_user),
  CONSTRAINT fk_score_utilisateur FOREIGN KEY (id_user) REFERENCES utilisateur (id_user) ON DELETE CASCADE,
  CONSTRAINT ck_score_positif CHECK (score >= 0),
  CONSTRAINT ck_niveau_positif CHECK (niveau >= 1)
);

-- ---------------------------------------------------------------------
-- Projets et listes
-- ---------------------------------------------------------------------
CREATE TABLE projet (
  id_projet    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nom          VARCHAR2(100) NOT NULL,
  description  VARCHAR2(1000),
  date_debut   DATE NOT NULL,
  date_fin     DATE,
  id_createur  NUMBER NOT NULL,                       -- CREER_PROJET (1,1)
  CONSTRAINT pk_projet PRIMARY KEY (id_projet),
  CONSTRAINT fk_projet_createur FOREIGN KEY (id_createur) REFERENCES utilisateur (id_user),
  CONSTRAINT ck_projet_dates CHECK (date_fin IS NULL OR date_fin >= date_debut)
);

CREATE TABLE liste_de_taches (
  id_liste   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  titre      VARCHAR2(100) NOT NULL,
  id_projet  NUMBER NOT NULL,                         -- COMPOSER (1,1)
  CONSTRAINT pk_liste PRIMARY KEY (id_liste),
  CONSTRAINT fk_liste_projet FOREIGN KEY (id_projet) REFERENCES projet (id_projet) ON DELETE CASCADE,
  CONSTRAINT uq_liste_titre UNIQUE (id_projet, titre)
);

-- ---------------------------------------------------------------------
-- Tâches : actives et terminées
-- Une tâche terminée est déplacée de TACHE_ACTIVE vers TACHE_TERMINEE,
-- ce qui garde la table des tâches en cours légère.
-- ---------------------------------------------------------------------
CREATE TABLE tache_active (
  id_tache      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  intitule      VARCHAR2(150) NOT NULL,
  categorie     VARCHAR2(50),
  description   VARCHAR2(1000),
  lien_externe  VARCHAR2(500),
  priorite      VARCHAR2(10) DEFAULT 'moyenne' NOT NULL,
  deadline      DATE,
  statut        VARCHAR2(10) DEFAULT 'a_faire' NOT NULL,
  dependante    NUMBER(1) DEFAULT 0 NOT NULL,         -- 1 si la tâche attend une tâche parente
  periodique    NUMBER(1) DEFAULT 0 NOT NULL,         -- 1 si la tâche se répète (voir PERIODE)
  id_liste      NUMBER,                               -- APPARTENIR_LISTE (0,1) : tâche hors liste possible
  id_createur   NUMBER NOT NULL,                      -- CREER_TACHE (1,1)
  CONSTRAINT pk_tache_active PRIMARY KEY (id_tache),
  CONSTRAINT fk_tache_liste FOREIGN KEY (id_liste) REFERENCES liste_de_taches (id_liste) ON DELETE SET NULL,
  CONSTRAINT fk_tache_createur FOREIGN KEY (id_createur) REFERENCES utilisateur (id_user),
  CONSTRAINT ck_tache_priorite CHECK (priorite IN ('basse', 'moyenne', 'haute')),
  CONSTRAINT ck_tache_statut CHECK (statut IN ('a_faire', 'en_cours', 'bloquee')),
  CONSTRAINT ck_tache_dependante CHECK (dependante IN (0, 1)),
  CONSTRAINT ck_tache_periodique CHECK (periodique IN (0, 1))
);

CREATE TABLE tache_terminee (
  id_tache      NUMBER,                               -- reprend l'identifiant de la tâche active
  intitule      VARCHAR2(150) NOT NULL,
  categorie     VARCHAR2(50),
  description   VARCHAR2(1000),
  lien_externe  VARCHAR2(500),
  priorite      VARCHAR2(10) NOT NULL,
  deadline      DATE,
  statut        VARCHAR2(10) DEFAULT 'terminee' NOT NULL,
  dependante    NUMBER(1) DEFAULT 0 NOT NULL,
  periodique    NUMBER(1) DEFAULT 0 NOT NULL,
  id_liste      NUMBER,
  id_createur   NUMBER NOT NULL,                      -- TERMINER (1,1) : utilisateur qui a clos la tâche
  date_fin      DATE DEFAULT SYSDATE NOT NULL,        -- ajouté pour mesurer les retards et la productivité
  CONSTRAINT pk_tache_terminee PRIMARY KEY (id_tache),
  CONSTRAINT fk_terminee_liste FOREIGN KEY (id_liste) REFERENCES liste_de_taches (id_liste) ON DELETE SET NULL,
  CONSTRAINT fk_terminee_utilisateur FOREIGN KEY (id_createur) REFERENCES utilisateur (id_user),
  CONSTRAINT ck_terminee_statut CHECK (statut = 'terminee'),
  CONSTRAINT ck_terminee_priorite CHECK (priorite IN ('basse', 'moyenne', 'haute'))
);

-- ASSIGNER (0,N – 0,N) : table d'association
CREATE TABLE assignation (
  id_assignation  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_user         NUMBER NOT NULL,
  id_tache        NUMBER NOT NULL,
  CONSTRAINT pk_assignation PRIMARY KEY (id_assignation),
  CONSTRAINT fk_assignation_user FOREIGN KEY (id_user) REFERENCES utilisateur (id_user) ON DELETE CASCADE,
  CONSTRAINT fk_assignation_tache FOREIGN KEY (id_tache) REFERENCES tache_active (id_tache) ON DELETE CASCADE,
  CONSTRAINT uq_assignation UNIQUE (id_user, id_tache)
);

-- REPETER (0,1 – 1,1) : une période par tâche périodique
CREATE TABLE periode (
  id_tache    NUMBER,
  date_debut  DATE NOT NULL,
  date_fin    DATE,
  intervalle  NUMBER(4) NOT NULL,                     -- en jours
  CONSTRAINT pk_periode PRIMARY KEY (id_tache),
  CONSTRAINT fk_periode_tache FOREIGN KEY (id_tache) REFERENCES tache_active (id_tache) ON DELETE CASCADE,
  CONSTRAINT ck_periode_intervalle CHECK (intervalle > 0),
  CONSTRAINT ck_periode_dates CHECK (date_fin IS NULL OR date_fin > date_debut)
);

-- DEPENDRE : une tâche dépendante attend une tâche parente
CREATE TABLE tache_parente (
  id_dep         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_dependante  NUMBER NOT NULL,
  id_parente     NUMBER NOT NULL,
  CONSTRAINT pk_tache_parente PRIMARY KEY (id_dep),
  CONSTRAINT fk_dep_dependante FOREIGN KEY (id_dependante) REFERENCES tache_active (id_tache) ON DELETE CASCADE,
  CONSTRAINT fk_dep_parente FOREIGN KEY (id_parente) REFERENCES tache_active (id_tache) ON DELETE CASCADE,
  CONSTRAINT uq_dependance UNIQUE (id_dependante, id_parente),
  CONSTRAINT ck_pas_auto_dependance CHECK (id_dependante <> id_parente)
);

-- Index sur les clés étrangères les plus utilisées dans les jointures
CREATE INDEX ix_tache_liste ON tache_active (id_liste);
CREATE INDEX ix_tache_createur ON tache_active (id_createur);
CREATE INDEX ix_tache_deadline ON tache_active (deadline);
CREATE INDEX ix_assignation_tache ON assignation (id_tache);
CREATE INDEX ix_liste_projet ON liste_de_taches (id_projet);

